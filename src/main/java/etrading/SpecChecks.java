    private static final class Rule {
        final String title;
        final Body body;

        Rule(String title, Body body) {
            this.title = title;
            this.body = body;
        }
    }

    public static void main(String[] args) {
        List<Rule> core = new ArrayList<>();
        core.add(new Rule("1. the published top of book is correct",
                SpecChecks::publishedTopOfBookIsCorrect));
        core.add(new Rule("2. quotes that must not count are excluded",
                SpecChecks::quotesThatMustNotCountAreExcluded));
        core.add(new Rule("3. an update is published exactly when top of book changes",
                SpecChecks::publishesExactlyWhenTopOfBookChanges));
        core.add(new Rule("4. safe under concurrent producers and consumers, and it stops",
                SpecChecks::safeUnderConcurrentProducersAndConsumers));
        core.add(new Rule("5. hot path allocates under 40 bytes per quote",
                SpecChecks::hotPathAllocatesUnder40BytesPerQuote));

        List<Rule> stretch = new ArrayList<>();
        stretch.add(new Rule("6. a crossed book is never published",
                SpecChecks::crossedBookIsNeverPublished));
        stretch.add(new Rule("7. hot path allocates almost nothing (under 16 bytes/quote)",
                SpecChecks::hotPathAllocatesAlmostNothing));

        System.out.println("Checking etrading.PriceAggregator against SPEC.md");
        System.out.println("(running; the report is printed at the end)");
        System.out.println();

        List<String> report = new ArrayList<>();
        int corePassed = runAll(core, report);
        int stretchPassed = runAll(stretch, report);

        System.out.flush();
        try {
            Thread.sleep(150L);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }

        StringBuilder out = new StringBuilder();
        out.append(System.lineSeparator());
        out.append("----------------------------------------------------------------")
                .append(System.lineSeparator());
        out.append("SPEC REPORT").append(System.lineSeparator());
        out.append("(any stack traces above came from the aggregator's own threads)")
                .append(System.lineSeparator());
        out.append("----------------------------------------------------------------")
                .append(System.lineSeparator());
        for (String line : report) {
            out.append(line).append(System.lineSeparator());
        }
        out.append("----------------------------------------------------------------")
                .append(System.lineSeparator());
        out.append(String.format("CORE     %d / %d passed%n", corePassed, core.size()));
        out.append(String.format("STRETCH  %d / %d passed%n", stretchPassed, stretch.size()));
        out.append("----------------------------------------------------------------")
                .append(System.lineSeparator());
        if (corePassed < core.size()) {
            out.append("Core rules are still violated. SPEC.md says what each rule requires.");
        } else if (stretchPassed < stretch.size()) {
            out.append("All core rules satisfied. Stretch rules remain.");
        } else {
            out.append("All rules satisfied.");
        }
        System.out.println(out);
        System.exit(corePassed == core.size() ? 0 : 1);
    }

    private static int runAll(List<Rule> rules, List<String> report) {
        int passed = 0;
        for (Rule rule : rules) {
            try {
                rule.body.run();
                report.add("[PASS] " + rule.title);
                passed++;
            } catch (AssertionError err) {
                report.add("[FAIL] " + rule.title);
                report.add("       " + err.getMessage());
            } catch (Exception ex) {
                report.add("[FAIL] " + rule.title);
                report.add("       threw " + describe(ex.getCause() == null ? ex : ex.getCause()));
            }
        }
        return passed;
    }

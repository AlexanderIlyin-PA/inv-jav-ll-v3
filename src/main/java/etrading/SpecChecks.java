    private interface Body {
        void run() throws Exception;
    }

    /**
     * Runs one check on a daemon thread and gives up after {@code timeoutMs}, so a
     * blocking call fails the check instead of hanging the whole run with no
     * output at all.
     */
    private static void guard(long timeoutMs, Body body) throws Exception {
        final Throwable[] thrown = new Throwable[1];
        Thread t = new Thread(() -> {
            try {
                body.run();
            } catch (Throwable x) {
                thrown[0] = x;
            }
        }, "spec-check");
        t.setDaemon(true);
        t.start();
        t.join(timeoutMs);
        if (t.isAlive()) {
            throw new AssertionError("the check did not return within " + (timeoutMs / 1000)
                    + "s, so something blocked. The usual cause is stop() waiting on the "
                    + "worker thread without interrupting it, or a getter holding a lock "
                    + "the worker needs.");
        }
        if (thrown[0] instanceof AssertionError) {
            throw (AssertionError) thrown[0];
        }
        if (thrown[0] instanceof RuntimeException) {
            throw (RuntimeException) thrown[0];
        }
        if (thrown[0] != null) {
            throw new Exception(thrown[0]);
        }
    }

    static boolean awaitTrue(BooleanSupplier condition, long timeoutMs) {
        long deadline = System.currentTimeMillis() + timeoutMs;
        while (System.currentTimeMillis() < deadline) {
            if (condition.getAsBoolean()) {
                return true;
            }
            try {
                Thread.sleep(2L);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
                return false;
            }
        }
        return condition.getAsBoolean();
    }

    static void assertEquals(double expected, double actual, String what) {
        if (Double.isNaN(expected) != Double.isNaN(actual)
                || (!Double.isNaN(expected) && Math.abs(expected - actual) > EPS)) {
            throw new AssertionError(String.format(
                    "%s: expected %.5f but was %.5f", what, expected, actual));
        }
    }

    static void assertEquals(int expected, int actual, String what) {
        if (expected != actual) {
            throw new AssertionError(String.format(
                    "%s: expected %d but was %d", what, expected, actual));
        }
    }

    private static String describe(Throwable t) {
        if (t == null) {
            return "(unknown)";
        }
        StackTraceElement[] trace = t.getStackTrace();
        String where = trace.length > 0 ? " at " + trace[0] : "";
        return t + where;
    }

    /** Counts callbacks. Used where only "did anything arrive" matters. */
    static final class Counter implements QuoteListener {
        private final AtomicInteger n = new AtomicInteger();

        @Override
        public void onBest(String symbol, double bestBid, double bestAsk, long ts) {
            n.incrementAndGet();
        }

        int count() {
            return n.get();
        }
    }

    /**
     * One aggregator plus a listener that records what was actually delivered,
     * torn down after each check.
     */
    static final class Fixture implements AutoCloseable {

        final PriceAggregatorApi agg;

        private final Object lock = new Object();
        private int publishCount;
        private String lastSymbol;
        private double lastBid = Double.NaN;
        private double lastAsk = Double.NaN;
        private final List<String> recent = new ArrayList<>();

        private final int uncaughtAtStart;

        Fixture() throws Exception {
            uncaughtAtStart = UNCAUGHT.get();
            agg = newAggregator();
            agg.addListener((symbol, bestBid, bestAsk, ts) -> {
                synchronized (lock) {
                    publishCount++;
                    lastSymbol = symbol;
                    lastBid = bestBid;
                    lastAsk = bestAsk;
                    if (recent.size() < 12) {
                        recent.add(String.format("%s %.5f/%.5f", symbol, bestBid, bestAsk));
                    }
                }
            });
            agg.start();
        }

        int publishes() {
            synchronized (lock) {
                return publishCount;
            }
        }

        void quote(String symbol, String lp, double bid, double ask, long tsNanos) {
            agg.onQuote(symbol, lp, bid, ask, tsNanos);
        }

        /** Fails the check if any thread the aggregator owns has died. */
        void assertHealthy() {
            if (UNCAUGHT.get() != uncaughtAtStart) {
                throw new AssertionError("the aggregator's worker thread died: "
                        + describe(lastUncaught));
            }
        }

        void awaitBestBid(double expected) {
            awaitTrue(() -> Math.abs(agg.getBestBid(SYM) - expected) <= EPS, 2_000);
            assertHealthy();
        }

        void awaitPublishes(int atLeast) {
            awaitTrue(() -> publishes() >= atLeast, 2_000);
            assertHealthy();
        }

        /** Long enough that any update would certainly have been observed. */
        void settle() {
            try {
                Thread.sleep(300L);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            }
            assertHealthy();
        }

        void assertPublished(String symbol, double bid, double ask, String what) {
            assertHealthy();
            synchronized (lock) {
                boolean ok = symbol.equals(lastSymbol)
                        && Math.abs(bid - lastBid) <= EPS
                        && Math.abs(ask - lastAsk) <= EPS;
                if (!ok) {
                    throw new AssertionError(String.format(
                            "%s: expected %s %.5f/%.5f but the last update delivered was "
                                    + "%s %.5f/%.5f. Updates so far: %s. The getters and "
                                    + "the published stream must agree.",
                            what, symbol, bid, ask, lastSymbol, lastBid, lastAsk,
                            recent.isEmpty() ? "(none)" : String.join(", ", recent)));
                }
            }
        }

        @Override
        public void close() {
            agg.stop();
        }
    }

